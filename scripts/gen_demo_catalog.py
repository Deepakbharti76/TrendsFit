#!/usr/bin/env python3
"""Generates the DEV-ONLY demo catalog (20 products) as Flyway SQL plus placeholder SVG images.
Demo rows are flagged is_demo=1 and are never loaded in production (profile 'prod' does not include db/seed-dev).
Run from the repo root: python3 scripts/gen_demo_catalog.py"""
import os, random
random.seed(7)
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IMG = os.path.join(ROOT, 'frontend', 'public', 'img', 'demo')
SQL = os.path.join(ROOT, 'backend', 'src', 'main', 'resources', 'db', 'seed-dev', 'V100__demo_catalog.sql')
os.makedirs(IMG, exist_ok=True)

COLORS = {'Indigo': '#2b3a67', 'Black': '#1c1c1e', 'Light Blue': '#8fb4d9', 'Grey': '#8a8d91', 'White': '#f3f1ec',
          'Navy': '#14213d', 'Olive': '#6b705c', 'Maroon': '#7b1e3a', 'Sand': '#d9c7a0', 'Sky': '#a9d6e5'}
JEANS = [('Slim Fit Stretch Jeans', 'Slim', 1499, 1199, ['Indigo', 'Black', 'Light Blue']),
         ('Straight Fit Classic Jeans', 'Straight', 1599, None, ['Indigo', 'Grey']),
         ('Relaxed Fit Denim Jeans', 'Relaxed', 1699, 1399, ['Light Blue', 'Black']),
         ('Tapered Fit Jeans', 'Tapered', 1549, None, ['Indigo', 'Black']),
         ('Loose Fit Baggy Jeans', 'Loose', 1799, 1499, ['Light Blue', 'Grey']),
         ('Skinny Fit Black Jeans', 'Skinny', 1399, None, ['Black']),
         ('Carpenter Fit Jeans', 'Relaxed', 1899, 1599, ['Indigo', 'Sand'])]
TEES = [('Essential Crew Neck T-Shirt', 'Regular', 599, 499, ['White', 'Black', 'Navy']),
        ('Oversized Drop Shoulder T-Shirt', 'Oversized', 799, 649, ['Black', 'Sand', 'Olive']),
        ('Slim Fit Polo T-Shirt', 'Slim', 899, None, ['Navy', 'Maroon']),
        ('Pocket T-Shirt', 'Regular', 649, None, ['Grey', 'White']),
        ('Henley T-Shirt', 'Regular', 749, 599, ['Olive', 'Black']),
        ('Graphic Print T-Shirt', 'Regular', 699, None, ['White', 'Black']),
        ('Longline Curved Hem T-Shirt', 'Relaxed', 729, 599, ['Grey', 'Sky'])]
SHIRTS = [('Oxford Casual Shirt', 'Regular', 1199, 999, ['Sky', 'White']),
          ('Slim Fit Cotton Shirt', 'Slim', 1299, None, ['Navy', 'White']),
          ('Linen Blend Shirt', 'Relaxed', 1499, 1299, ['Sand', 'Olive']),
          ('Checked Flannel Shirt', 'Regular', 1399, None, ['Maroon', 'Navy']),
          ('Mandarin Collar Shirt', 'Slim', 1249, 1049, ['Black', 'White']),
          ('Denim Shirt', 'Regular', 1599, None, ['Indigo', 'Light Blue'])]
SIZES_BOTTOM = ['28', '30', '32', '34', '36']
SIZES_TOP = ['S', 'M', 'L', 'XL', 'XXL']

def shade(hexc, f):
    h = hexc.lstrip('#'); r, g, b = [int(h[i:i+2], 16) for i in (0, 2, 4)]
    return '#%02x%02x%02x' % tuple(max(0, min(255, int(c * f))) for c in (r, g, b))

def svg(kind, color, view):
    c = COLORS[color]; d = shade(c, 0.78)
    bg = '#efece6'
    if kind == 'jeans':
        shape = (f'<path d="M150 90 L450 90 L470 240 L440 700 L330 700 L300 300 L270 700 L160 700 L130 240 Z" fill="{c}"/>'
                 f'<path d="M150 90 L450 90 L455 130 L145 130 Z" fill="{d}"/><path d="M300 130 L300 300" stroke="{d}" stroke-width="4"/>'
                 f'<path d="M180 150 q40 30 70 0" stroke="{d}" stroke-width="3" fill="none"/><path d="M350 150 q40 30 70 0" stroke="{d}" stroke-width="3" fill="none"/>')
    elif kind == 'tshirt':
        shape = (f'<path d="M210 110 L120 170 L160 260 L215 235 L215 690 L385 690 L385 235 L440 260 L480 170 L390 110 Q300 170 210 110 Z" fill="{c}"/>'
                 f'<path d="M210 110 Q300 170 390 110 L385 135 Q300 195 215 135 Z" fill="{d}"/>')
    else:
        shape = (f'<path d="M210 110 L110 180 L150 290 L215 262 L215 700 L385 700 L385 262 L450 290 L490 180 L390 110 L300 200 Z" fill="{c}"/>'
                 f'<path d="M210 110 L300 200 L390 110 L350 100 L300 150 L250 100 Z" fill="{d}"/><path d="M300 200 L300 700" stroke="{d}" stroke-width="4"/>'
                 + ''.join(f'<circle cx="300" cy="{y}" r="5" fill="{d}"/>' for y in (260, 340, 420, 500, 580, 660)))
    if view == 'detail':
        shape = f'<g transform="translate(-150 -120) scale(1.5)">{shape}</g>'
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 600 800" role="img" aria-label="{kind} in {color} (demo image)">'
            f'<rect width="600" height="800" fill="{bg}"/>{shape}'
            f'<text x="20" y="780" font-family="Arial,sans-serif" font-size="18" fill="#8a8680">DEMO IMAGE - replace with real product photo</text></svg>')

def esc(s): return s.replace("'", "''")
rows = []; sql = ['-- DEV ONLY demo catalog (generated by scripts/gen_demo_catalog.py). Not real stock. Never loaded in production.\n']
pid = 0; n = {'jeans': 0, 'tshirt': 0, 'shirt': 0}
cat_slug = {'jeans': 'jeans', 'tshirt': 't-shirts', 'shirt': 'shirts'}
mat = {'jeans': '98% Cotton, 2% Elastane denim', 'tshirt': '100% Combed Cotton, 180 GSM', 'shirt': '100% Cotton'}
care = {'jeans': 'Machine wash cold with similar colours. Do not bleach. Tumble dry low. Iron on reverse.',
        'tshirt': 'Machine wash cold. Do not bleach. Tumble dry low. Iron on reverse, do not iron the print.',
        'shirt': 'Machine wash cold. Do not bleach. Dry in shade. Warm iron.'}
chart = {'jeans': 'Size|Waist (in)|Hip (in)|Length (in)\n28|28|36|39\n30|30|38|40\n32|32|40|41\n34|34|42|41\n36|36|44|42',
         'tshirt': 'Size|Chest (in)|Length (in)|Shoulder (in)\nS|38|26|17\nM|40|27|18\nL|42|28|19\nXL|44|29|20\nXXL|46|30|21',
         'shirt': 'Size|Chest (in)|Length (in)|Sleeve (in)\nS|38|28|24\nM|40|29|25\nL|42|30|25.5\nXL|44|31|26\nXXL|46|32|26.5'}
for kind, items in (('jeans', JEANS), ('tshirt', TEES), ('shirt', SHIRTS)):
    for i, (name, fit, price, sale, colors) in enumerate(items):
        pid += 1; n[kind] += 1
        slug = name.lower().replace(' ', '-')
        sku = f"TF-{kind[:2].upper()}-{n[kind]:03d}"
        sizes = SIZES_BOTTOM if kind == 'jeans' else SIZES_TOP
        flags = dict(f=int(i < 2), n=int(i in (0, 3)), b=int(i in (1, 2)))
        desc = f"{name}: a clean, comfortable {fit.lower()} fit made for everyday wear. (Demo product for development only.)"
        sql.append(f"INSERT INTO products (slug,name,sku,category_id,description,fit,material,care,size_chart,price,sale_price,seo_title,seo_description,status,is_featured,is_new_arrival,is_bestseller,is_demo,sold_count) VALUES "
                   f"('{slug}','{esc(name)}','{sku}',(SELECT id FROM categories WHERE slug='{cat_slug[kind]}'),'{esc(desc)}','{fit}','{mat[kind]}','{esc(care[kind])}','{esc(chart[kind])}',{price},{sale if sale else 'NULL'},'{esc(name)} | TrendsFit','{esc(desc)}','ACTIVE',{flags['f']},{flags['n']},{flags['b']},1,{random.randint(5, 120)});")
        for v, view in enumerate(('front', 'detail')):
            fn = f"{slug}-{v+1}.svg"
            open(os.path.join(IMG, fn), 'w').write(svg(kind, colors[0], view))
            sql.append(f"INSERT INTO product_images (product_id,url,alt,sort_order) VALUES ((SELECT id FROM products WHERE slug='{slug}'),'/img/demo/{fn}','{esc(name)} {view} view (demo)',{v});")
        for color in colors:
            for size in sizes:
                vsku = f"{sku}-{color.upper().replace(' ', '')[:3]}-{size}"
                stock = random.choice([0, 3, 5, 8, 12, 20]) if random.random() < 0.9 else 0
                sql.append(f"INSERT INTO product_variants (product_id,sku,size,color,color_hex,stock) VALUES ((SELECT id FROM products WHERE slug='{slug}'),'{vsku}','{size}','{color}','{COLORS[color]}',{stock});")
open(SQL, 'w').write('\n'.join(sql) + '\n')
print('products:', pid, 'sql lines:', len(sql))
